DATABASE_URL = os.environ.get("DATABASE_URL")

def get_db():
    """Open a PostgreSQL connection. Rows are returned as dictionaries."""
    if not DATABASE_URL:
        raise RuntimeError(
            "DATABASE_URL is not set. Configure it in your environment."
        )

    return psycopg.connect(
        DATABASE_URL,
        sslmode="require",
        row_factory=dict_row,
    )


def init_database():
    """Create tables if they do not already exist."""
    with get_db() as conn:
        with conn.cursor() as cursor:
            cursor.execute("""
                CREATE TABLE IF NOT EXISTS users (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    username VARCHAR(100) UNIQUE NOT NULL,
                    email VARCHAR(255) UNIQUE NOT NULL,
                    password VARCHAR(255) NOT NULL
                )
            """)

            cursor.execute("""
                CREATE TABLE IF NOT EXISTS analysis_history (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    user_id BIGINT NOT NULL REFERENCES users(id)
                        ON DELETE CASCADE,
                    message TEXT NOT NULL,
                    spam_result VARCHAR(50) NOT NULL,
                    toxic_result VARCHAR(50) NOT NULL,
                    overall_result VARCHAR(100) NOT NULL,
                    analysis_type VARCHAR(20) NOT NULL DEFAULT 'Single',
                    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
                )
            """)


# Runs on import, so gunicorn (used on Render) also creates the tables.
# CREATE TABLE IF NOT EXISTS makes this safe to repeat.
init_database()


