@app.route("/download", methods=["POST"])
@login_required
def download():
    batch_text = request.form.get("batch_messages", "").strip()
    messages = [
        line.strip() for line in batch_text.splitlines() if line.strip()
    ]

    output = io.StringIO()
    writer = csv.writer(output)
    writer.writerow([
        "ID", "Message", "Spam Detection",
        "Toxic Detection", "Overall Result",
    ])

    for number, message in enumerate(messages, start=1):
        result = analyze_message(message)
        writer.writerow([
            number,
            message,
            result["spam"],
            result["toxic"],
            result["overall"],
        ])

    response = Response(output.getvalue(), mimetype="text/csv")
    response.headers["Content-Disposition"] = (
        "attachment; filename=analysis_results.csv"
    )
    return response


