@app.route("/batch", methods=["POST"])
@login_required
def batch():
    batch_text = request.form.get("batch_messages", "").strip()

    if not batch_text:
        return render_template(
            "index.html",
            error="Please enter at least one message.",
            mode="batch",
        )

    messages = [
        line.strip() for line in batch_text.splitlines() if line.strip()
    ]

    results = []
    for number, message in enumerate(messages, start=1):
        result = analyze_message(message)
        results.append({
            "id": number,
            "message": message,
            "spam": result["spam"],
            "toxic": result["toxic"],
            "overall": result["overall"],
        })

    # Save in reverse so the first submitted message appears first in history.
    for item in reversed(results):
        save_analysis(
            item["message"],
            {
                "spam": item["spam"],
                "toxic": item["toxic"],
                "overall": item["overall"],
            },
            "Batch",
        )

    return render_template(
        "index.html",
        batch_results=results,
        batch_count=len(results),
        mode="batch",
    )


