# SAVE TO DATABASE
# ============================================================

def save_analysis(message, result, analysis_type="Single"):
    user_id = session.get("user_id")
    if not user_id:
        return

    with get_db() as conn:
        with conn.cursor() as cursor:
            cursor.execute(
                """
                INSERT INTO analysis_history
                    (user_id, message, spam_result, toxic_result,
                     overall_result, analysis_type)
                VALUES (%s, %s, %s, %s, %s, %s)
                """,
                (
                    user_id,
                    message,
                    result["spam"],
                    result["toxic"],
                    result["overall"],
                    analysis_type,
                ),
            )


